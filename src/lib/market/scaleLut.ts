export function posToYMilli(posY: number): number {
  const i = Math.max(0, Math.min(1000, Math.round(posY)));
  return LUT_Y[i];
}

export function candleCountToPos(candles: number): number {
  // Binary search for nearest entry
  let lo = 0, hi = 1000;
  while (lo < hi) {
    const mid = (lo + hi) >> 1;
    if (LUT_X[mid] < candles) lo = mid + 1;
    else hi = mid;
  }
  return lo;
}

export function yMilliToPos(yMilli: number): number {
  let lo = 0, hi = 1000;
  while (lo < hi) {
    const mid = (lo + hi) >> 1;
    if (LUT_Y[mid] < yMilli) lo = mid + 1;
    else hi = mid;
  }
  return lo;
}
